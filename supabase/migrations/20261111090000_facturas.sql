-- ═══════════════════════════════════════════════════════════════════════════
-- Facturas (cuentas de cobro) de los reportes de comisiones.
--
-- Flujo del software anterior: se crea el reporte de comisiones de la
-- aseguradora y luego se le hace una FACTURA a esas líneas (abonos). La factura
-- suma la comisión de las líneas (subtotal), calcula IVA, retención en la
-- fuente e ICA, y da el valor a consignar:
--     total   = subtotal + IVA
--     neto    = total − retención − ICA        (el "Vlr a consignar")
--
-- · facturas_empresas  razones sociales de cada aseguradora; siempre se
--                      identifican por el NIT (nit_norm único).
-- · facturacion_config porcentajes por defecto (IVA, retención, ICA). Los edita
--                      el Administrador; cada factura guarda su copia y se
--                      puede cambiar en esa factura.
-- · facturas           cabecera; abonos_poliza.idfactura la enlaza con sus líneas.
--                      id es "generated by default" para poder cargar el
--                      historial del software anterior conservando su código.
--
-- OJO: abonos_poliza.num_factura NO se toca: es el recibo/factura que trae el
-- reporte de la aseguradora, no nuestro número de factura.
--
-- · IVA por empresa: cada empresa aseguradora trae su IVA (16 % las de Generales,
--   0 % las de Vida): al elegirla en la factura el IVA parte de ese valor.
-- · Retención de IVA (reteiva): en el software anterior, a 55 facturas con IVA se
--   les restaba además la mitad del IVA al valor a consignar. Se conserva como un
--   porcentaje más (0 por defecto):
--     neto = total − retención − ICA − retención de IVA
-- · El prefijo de la factura nueva es el de la última factura cargada (el software
--   anterior terminó en el prefijo 2, número 2730).
--
-- Quién puede: A, S y D crean y editan; solo A elimina.
-- Se puede volver a correr sin problema. Correr primero en PRUEBAS.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── Empresas aseguradoras (por NIT) ────────────────────────────────────────
create table if not exists facturas_empresas (
  id        bigint generated always as identity primary key,
  aseg_id   bigint references aseguradoras(id),
  nombre    text not null,
  nit       text not null,
  nit_norm  text generated always as (regexp_replace(nit, '\D', '', 'g')) stored,
  iva_pct   numeric not null default 0 check (iva_pct >= 0 and iva_pct <= 100),
  activa    boolean not null default true,
  fcreado   timestamptz not null default now()
);
alter table facturas_empresas add column if not exists iva_pct numeric not null default 0;
alter table facturas_empresas drop constraint if exists facturas_empresas_nit_ck;
create unique index if not exists facturas_empresas_nit_uq on facturas_empresas (nit_norm);
create index if not exists facturas_empresas_aseg_idx on facturas_empresas (aseg_id);

-- ── Porcentajes por defecto ────────────────────────────────────────────────
create table if not exists facturacion_config (
  clave  text primary key,
  valor  numeric not null check (valor >= 0 and valor <= 100)
);
insert into facturacion_config (clave, valor) values
  ('iva_pct', 0), ('retefuente_pct', 10), ('ica_pct', 0)
on conflict (clave) do nothing;

-- ── Cabecera de la factura ─────────────────────────────────────────────────
create table if not exists facturas (
  id              bigint generated by default as identity primary key,
  prefijo         int  not null default 1,        -- lo genera el sistema
  num_factura     int  not null,
  fecha           date not null default current_date,
  aseg_id         bigint references aseguradoras(id),
  interm_id       bigint references intermediarios(id),
  empresa_id      bigint references facturas_empresas(id),
  observacion     text,
  subtotal        numeric not null default 0,
  iva_pct         numeric not null default 0,
  iva             numeric not null default 0,
  retefuente_pct  numeric not null default 0,
  retefuente      numeric not null default 0,
  ica_pct         numeric not null default 0,
  ica             numeric not null default 0,
  reteiva_pct     numeric not null default 0,     -- retención de IVA (sobre el IVA)
  reteiva         numeric not null default 0,
  total           numeric not null default 0,     -- subtotal + IVA
  neto            numeric not null default 0,     -- total − retención − ICA − retención de IVA
  estado          char(1) not null default 'A' check (estado in ('A', 'C', 'R', 'P', 'N')),
  usuario_id      bigint references usuarios(id),
  fcreado         timestamptz not null default now(),
  fultmod         timestamptz not null default now(),
  constraint facturas_numero_uq unique (prefijo, num_factura)
);
alter table facturas add column if not exists reteiva_pct numeric not null default 0;
alter table facturas add column if not exists reteiva numeric not null default 0;
create index if not exists facturas_aseg_idx on facturas (aseg_id);
create index if not exists facturas_estado_idx on facturas (estado);
create index if not exists facturas_fecha_idx on facturas (fecha desc);
create index if not exists abonos_poliza_idfactura_idx on abonos_poliza (idfactura);

-- Las líneas viejas apuntan a facturas que todavía no están cargadas: la
-- restricción se crea sin revisar lo existente y solo vigila lo nuevo. Cuando
-- se importe el historial se puede validar con:
--   alter table abonos_poliza validate constraint abonos_poliza_idfactura_fk;
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'abonos_poliza_idfactura_fk') then
    alter table abonos_poliza
      add constraint abonos_poliza_idfactura_fk
      foreign key (idfactura) references facturas(id) on delete set null not valid;
  end if;
end $$;

create or replace function facturas_tocar()
returns trigger
language plpgsql
as $$
begin
  new.fultmod := now();
  return new;
end;
$$;
drop trigger if exists facturas_tocar_trg on facturas;
create trigger facturas_tocar_trg before update on facturas
  for each row execute function facturas_tocar();

